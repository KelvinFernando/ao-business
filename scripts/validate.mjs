import { createServer } from 'vite'
import { chromium } from 'playwright-core'
import { readFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const source = await readFile(`${root}src/flow/registry.ts`, 'utf8')
const routes = [...source.matchAll(/\bs\('([^']+)'/g)].map(match => match[1])
const server = await createServer({ root, server: { host: '127.0.0.1', port: 4173, strictPort: true }, logLevel: 'error' })
await server.listen()
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', error => errors.push(`pageerror: ${error.message}`))
page.on('console', message => { if (message.type() === 'error') errors.push(`console: ${message.text()}`) })
await mkdir(`${root}validation`, { recursive: true })
const failures = []
for (const route of routes) {
  await page.goto(`http://127.0.0.1:4173/#/${route}?v=default`)
  await page.waitForTimeout(80)
  const h1 = await page.locator('h1').count()
  if (h1 !== 1) failures.push(`${route}: expected 1 H1, found ${h1}`)
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
  if (overflow) failures.push(`${route}: horizontal overflow`)
}
for (const route of ['02-1-prequal','04-1-business-details','05-1-people-under','09-1-review','09-2-edit-business','10-1-status-waiting-signer','11-5-signer-personal-info']) {
  await page.goto(`http://127.0.0.1:4173/#/${route}?v=default`)
  await page.screenshot({ path: `${root}validation/${route}.png`, fullPage: false })
}
const clickButton = async (name) => { await page.getByRole('button', { name, exact: true }).click(); await page.waitForTimeout(100) }
await page.goto('http://127.0.0.1:4173/#/02-0-start?v=default')
await clickButton('Start my application')
if (!page.url().includes('02-1-prequal')) failures.push('happy path: start did not reach prequalification')
await clickButton('Continue')
if (!page.url().includes('02-2-eligible')) failures.push('happy path: prequalification did not reach eligible')
await page.goto('http://127.0.0.1:4173/#/02-6-verify-phone?v=default')
await page.locator('.otp-input').fill('123456')
await clickButton('Confirm')
if (!page.url().includes('03-1-prepare')) failures.push('happy path: correct OTP did not reach prepare')
await page.goto('http://127.0.0.1:4173/#/03-2-consent?v=default')
await clickButton('Agree and continue')
if (await page.locator('.error-summary').count() !== 1) failures.push('consent: missing error summary')
for (const label of await page.locator('.checkbox-row').all()) await label.click()
await clickButton('Agree and continue')
if (!page.url().includes('04-1-business-details')) failures.push('consent: valid form did not continue')
await page.goto('http://127.0.0.1:4173/#/05-1-people-under?v=default')
await clickButton('Continue')
if (await page.locator('.error-summary').count() !== 1) failures.push('ownership: under 100 did not block')
await page.goto('http://127.0.0.1:4173/#/05-1-people-exact?v=default')
await clickButton('Continue')
if (!page.url().includes('05-3-signing')) failures.push('ownership: exact 100 did not continue')
await page.goto('http://127.0.0.1:4173/#/07-2-declarations?v=default')
await clickButton('Continue')
if (!page.url().includes('07-3-declarations-error')) failures.push('declarations: unanswered PEP did not show error')
await page.goto('http://127.0.0.1:4173/#/04-2-address?v=default')
await page.locator('.screen-jump').click()
await clickButton('No results')
if (await page.getByText('No addresses found. Check what you typed or enter it manually.', { exact: true }).count() !== 1) failures.push('address: no-results simulation failed')
await clickButton('Show suggestions')
if (await page.locator('.address-results').getByRole('option').count() !== 3) failures.push('address: suggestion simulation failed')
await page.goto('http://127.0.0.1:4173/#/04-5-documents?v=default')
await page.locator('.screen-jump').click()
await clickButton('Upload succeeds')
await clickButton('Continue')
if (!page.url().includes('05-1-people-under')) failures.push('documents: successful upload did not enable continuation')
await page.goto('http://127.0.0.1:4173/#/04-5-documents?v=default')
await page.locator('.screen-jump').click()
await clickButton('Upload fails')
await clickButton('Continue')
if (!page.url().includes('04-6-documents-error')) failures.push('documents: failed upload did not reach error state')
await page.goto('http://127.0.0.1:4173/#/09-2-edit-business?v=default')
await clickButton('Save and return to review')
if (!page.url().includes('09-3-review-dependency')) failures.push('review edit: industry change did not flag dependency')
if (await page.getByText('1 section needs your attention', { exact: true }).count() !== 1) failures.push('review edit: dependency alert missing')
await page.goto('http://127.0.0.1:4173/#/09-6-agreement?v=default')
await clickButton('Accept and submit')
if (await page.locator('.error-summary').count() !== 1) failures.push('agreement: missing validation summary')
for (const label of await page.locator('.checkbox-row').all()) await label.click()
await page.locator('#signature').fill('Marie Tremblay')
await page.locator('.screen-jump').click()
await clickButton('Next submit fails')
await clickButton('Accept and submit')
await page.waitForTimeout(1350)
if (!page.url().includes('09-5-submit-failed')) failures.push('agreement: simulated submission failure did not open failure state')
if (await page.locator('#signature').inputValue() !== 'Marie Tremblay') failures.push('agreement: submission failure did not preserve signature')
await clickButton('Accept and submit')
await page.waitForTimeout(1350)
if (!page.url().includes('09-4-submitted')) failures.push('agreement: retry after failure did not succeed')
await page.goto('http://127.0.0.1:4173/#/11-1-invitation-email?v=default')
await clickButton('Continue my application')
if (!page.url().includes('11-2-verify-code')) failures.push('signer: invitation did not reach code screen')
await page.goto('http://127.0.0.1:4173/#/11-5-signer-personal-info?v=default')
await clickButton('Continue')
if (await page.locator('.error-summary').count() !== 1) failures.push('signer: missing accuracy confirmation did not block')
await page.locator('label:has(#signerConfirm)').click()
await clickButton('Continue')
if (!page.url().includes('11-6-signer-identity')) failures.push('signer: confirmed personal info did not reach identity')
await clickButton('Continue on this computer')
if (!page.url().includes('11-7-signer-agreement')) failures.push('signer: identity continuation did not reach agreement')
await page.goto('http://127.0.0.1:4173/#/02-1-prequal?v=default')
await page.locator('.screen-jump').click()
await page.getByLabel('Find a screen').fill('Account open')
await page.getByRole('option').click()
if (!page.url().includes('10-4-account-open')) failures.push('glass: searchable jumper failed')
await page.keyboard.press('Alt+ArrowRight')
await page.waitForTimeout(150)
if (!page.url().includes('10-5-not-approved')) failures.push(`glass: Alt+ArrowRight failed at ${page.url()}`)
await page.goto('http://127.0.0.1:4173/#/02-1-prequal?clean=1')
if (await page.locator('[data-prototype-control]').count() !== 0) failures.push('clean mode: presenter control is still visible')
console.log(JSON.stringify({ routes: routes.length, failures, errors: [...new Set(errors)] }, null, 2))
await browser.close()
await server.close()
if (failures.length || errors.length) process.exitCode = 1
